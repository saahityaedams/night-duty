// Writes dist/sw.js: precaches every built file so the game works offline after the first visit.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';

const dist = 'dist';
const files = [];
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(relative(dist, p).split('\\').join('/'));
  }
};
walk(dist);
const skip = new Set(['sw.js', '_headers']);
const assets = files.filter((f) => !skip.has(f));
// Bump SW_REV when this file's caching logic changes, so phones pick up the new worker.
const SW_REV = 'sw-2';
const hash = createHash('sha256').update(SW_REV);
for (const f of assets.sort()) hash.update(f).update(readFileSync(join(dist, f)));
const version = hash.digest('hex').slice(0, 12);
const list = ['./', ...assets.map((f) => `./${f}`)];
writeFileSync(
  join(dist, 'sw.js'),
  `// Generated by tools/gen-sw.mjs. Cache version ${version}.
const CACHE = 'nightduty-${version}';
const ASSETS = ${JSON.stringify(list)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(e.request).catch(() => caches.match('./'))),
  );
});
`,
);
console.log(`sw.js: ${list.length} files, version ${version}`);
